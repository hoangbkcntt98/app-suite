# Sets global: CHOSEN_IDS, CHOSEN_NAMES, CHOSEN_DESCS, CHOSEN_CTX
declare -a CHOSEN_IDS=()
declare -a CHOSEN_NAMES=()
declare -a CHOSEN_DESCS=()
declare -a CHOSEN_CTX=()

choose_models() {
    local total=${#SOURCE_IDS[@]}
    local page_size=15
    local cursor=0 scroll=0 i
    local checked=()
    for (( i=0; i<total; i++ )); do checked[$i]=0; done

    local labels=()
    for i in "${!SOURCE_IDS[@]}"; do
        if [[ "${SOURCE_NAMES[$i]}" == "${SOURCE_IDS[$i]}" ]]; then
            labels+=("${SOURCE_IDS[$i]}")
        else
            labels+=("${SOURCE_NAMES[$i]} [${SOURCE_IDS[$i]}]")
        fi
    done

    tput civis 2>/dev/null || true

    _count_checked() {
        local c=0 v
        for v in "${checked[@]}"; do [[ $v -eq 1 ]] && c=$(( c + 1 )) || true; done
        echo "$c"
    }

    _render_mdl() {
        local vis_end=$(( scroll + page_size ))
        [[ $vis_end -gt $total ]] && vis_end=$total

        echo ""
        echo -e "  ${WHITE}Select models ($total available)  |  ${DARK_GRAY}[Up/Down] navigate  [Space] toggle  [A] all  [N] none  [Enter] confirm${NC}"
        echo -e "  ${CYAN}Checked: $(_count_checked) / $total${NC}"
        echo ""

        for (( i=scroll; i<vis_end; i++ )); do
            local box="[ ]"; [[ ${checked[$i]} -eq 1 ]] && box="[x]"
            if [[ $i -eq $cursor ]]; then
                echo -e "  ${YELLOW}> $box ${labels[$i]}${NC}"
            else
                echo -e "    ${GRAY}$box${NC} ${labels[$i]}"
            fi
        done

        local remaining=$(( total - vis_end ))
        if [[ $remaining -gt 0 ]]; then
            echo ""
            echo -e "  ${DARK_YELLOW}... $remaining more model(s) below (scroll down) ...${NC}"
            echo ""
        else
            echo ""
        fi
    }

    _lines_mdl() {
        local vis_end=$(( scroll + page_size ))
        [[ $vis_end -gt $total ]] && vis_end=$total
        local n=$(( 4 + vis_end - scroll ))
        local remaining=$(( total - vis_end ))
        [[ $remaining -gt 0 ]] && n=$(( n + 3 )) || n=$(( n + 1 ))
        echo "$n"
    }

    _clear_mdl() {
        local n j
        n=$(_lines_mdl)
        for (( j=0; j<n; j++ )); do tput cuu1 2>/dev/null; tput el 2>/dev/null || true; done
    }

    _render_mdl

    local key seq vis_end
    while true; do
        IFS= read -rsn1 key || true

        if [[ "$key" == $'\x1b' ]]; then
            IFS= read -rsn2 -t 0.1 seq || true
            case "$seq" in
                '[A')  # Up
                    if [[ $cursor -gt 0 ]]; then
                        cursor=$(( cursor - 1 ))
                        [[ $cursor -lt $scroll ]] && scroll=$cursor
                    fi
                    ;;
                '[B')  # Down
                    if [[ $cursor -lt $(( total - 1 )) ]]; then
                        cursor=$(( cursor + 1 ))
                        vis_end=$(( scroll + page_size ))
                        if [[ $cursor -ge $vis_end ]]; then
                            scroll=$(( cursor - page_size + 1 ))
                            [[ $scroll -lt 0 ]] && scroll=0
                        fi
                    fi
                    ;;
                '[5')  # Page Up
                    IFS= read -rsn1 -t 0.1 || true
                    cursor=$(( cursor - page_size ))
                    [[ $cursor -lt 0 ]] && cursor=0
                    [[ $cursor -lt $scroll ]] && scroll=$cursor
                    ;;
                '[6')  # Page Down
                    IFS= read -rsn1 -t 0.1 || true
                    cursor=$(( cursor + page_size ))
                    [[ $cursor -ge $total ]] && cursor=$(( total - 1 ))
                    vis_end=$(( scroll + page_size ))
                    if [[ $cursor -ge $vis_end ]]; then
                        scroll=$(( cursor - page_size + 1 ))
                        [[ $scroll -lt 0 ]] && scroll=0
                    fi
                    ;;
            esac

        elif [[ "$key" == " " ]]; then
            if [[ ${checked[$cursor]} -eq 0 ]]; then
                checked[$cursor]=1
            else
                checked[$cursor]=0
            fi

        elif [[ "$key" == "a" || "$key" == "A" ]]; then
            for (( i=0; i<total; i++ )); do checked[$i]=1; done

        elif [[ "$key" == "n" || "$key" == "N" ]]; then
            for (( i=0; i<total; i++ )); do checked[$i]=0; done

        elif [[ "$key" == "" ]]; then
            _clear_mdl
            tput cnorm 2>/dev/null || true

            CHOSEN_IDS=(); CHOSEN_NAMES=(); CHOSEN_DESCS=(); CHOSEN_CTX=()
            for (( i=0; i<total; i++ )); do
                if [[ ${checked[$i]} -eq 1 ]]; then
                    CHOSEN_IDS+=("${SOURCE_IDS[$i]}")
                    CHOSEN_NAMES+=("${SOURCE_NAMES[$i]}")
                    CHOSEN_DESCS+=("${SOURCE_DESCS[$i]}")
                    CHOSEN_CTX+=("${SOURCE_CTX[$i]}")
                fi
            done

            if [[ ${#CHOSEN_IDS[@]} -eq 0 ]]; then
                CHOSEN_IDS+=("${SOURCE_IDS[$cursor]}")
                CHOSEN_NAMES+=("${SOURCE_NAMES[$cursor]}")
                CHOSEN_DESCS+=("${SOURCE_DESCS[$cursor]}")
                CHOSEN_CTX+=("${SOURCE_CTX[$cursor]}")
            fi

            echo ""
            write_ok "Selected ${#CHOSEN_IDS[@]} model(s): $(IFS=, ; echo "${CHOSEN_IDS[*]}")"
            write_ok "Default model: ${CHOSEN_IDS[0]}"
            return 0
        fi

        _clear_mdl
        _render_mdl
    done
}

