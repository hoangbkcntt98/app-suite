choose_source() {
    local combo_idx=() i
    for i in "${!MODEL_OWNED_BY[@]}"; do
        [[ "${MODEL_OWNED_BY[$i]}" == "combo" ]] && combo_idx+=("$i") || true
    done

    local options=() option_types=()
    if [[ ${#combo_idx[@]} -gt 0 ]]; then
        options+=("Combo models only (${#combo_idx[@]} models)")
        option_types+=("combo")
    fi
    options+=("All models (${#MODEL_IDS[@]} models)")
    option_types+=("all")

    local n_opts=${#options[@]}
    local cursor=0

    tput civis 2>/dev/null || true

    _render_src() {
        local j
        for j in "${!options[@]}"; do
            if [[ $j -eq $cursor ]]; then
                echo -e "  ${YELLOW}> ${options[$j]}${NC}"
            else
                echo    "    ${options[$j]}"
            fi
        done
    }

    _clear_src() {
        local j
        for j in "${!options[@]}"; do
            tput cuu1 2>/dev/null; tput el 2>/dev/null || true
        done
    }

    write_head "Model source"
    echo ""
    echo -e "  ${DARK_GRAY}[Up/Down] navigate  [Enter] confirm${NC}"
    echo ""
    _render_src

    local key seq
    while true; do
        IFS= read -rsn1 key || true
        if [[ "$key" == $'\x1b' ]]; then
            IFS= read -rsn2 -t 0.1 seq || true
            case "$seq" in
                '[A')
                    if [[ $cursor -gt 0 ]]; then
                        cursor=$(( cursor - 1 ))
                    fi
                    ;;
                '[B')
                    if [[ $cursor -lt $(( n_opts - 1 )) ]]; then
                        cursor=$(( cursor + 1 ))
                    fi
                    ;;
            esac
        elif [[ "$key" == "" ]]; then
            _clear_src
            tput cnorm 2>/dev/null || true
            echo ""
            write_ok "Source: ${options[$cursor]}"

            SOURCE_IDS=(); SOURCE_NAMES=(); SOURCE_DESCS=(); SOURCE_OWNED_BY=(); SOURCE_CTX=()
            if [[ "${option_types[$cursor]}" == "combo" ]]; then
                for i in "${combo_idx[@]}"; do
                    SOURCE_IDS+=("${MODEL_IDS[$i]}")
                    SOURCE_NAMES+=("${MODEL_NAMES[$i]}")
                    SOURCE_DESCS+=("${MODEL_DESCS[$i]}")
