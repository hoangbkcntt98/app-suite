install_9router() {
    [[ -d "$CODEX_HOME_DIR" ]] || die "Codex directory not found: $CODEX_HOME_DIR\nRun Codex once first."

    # Base URL
    local url="${BASE_URL:-}"
    if [[ -z "$url" ]]; then
        read -rp "Enter 9Router Base URL (e.g. http://127.0.0.1:20128/v1): " url
    fi
    url="${url%/}"
    [[ -z "$url" ]] && die "Base URL is empty."

    # API key Ã¢â‚¬â€ show existing value when present.
    local key=""
    local existing_key="${NINEROUTER_API_KEY:-}"
    if [[ -n "$existing_key" ]]; then
        local masked="${existing_key:0:6}..."
        echo -e "  ${DARK_YELLOW}Current $ENV_KEY_NAME: $masked${NC}"
        echo -e "  ${DARK_GRAY}Press Enter to keep current key, or type a new one.${NC}"
        read -rp "Enter 9Router API Key: " key
        [[ -z "$key" ]] && key="$existing_key"
    else
        read -rp "Enter 9Router API Key: " key
    fi
    [[ -z "$key" ]] && die "API key is empty."
    [[ "$key" == *$'\n'* || "$key" == *$'\r'* ]] && die "API key contains newline."

    # A child script cannot update parent shell environment. Persist key for new
    # shell sessions, systemd user services, and VS Code Remote reconnects.
    export NINEROUTER_API_KEY="$key"

    local env_dir="$HOME/.config/environment.d"
    local env_file="$env_dir/90-ninerouter.conf"
    mkdir -p "$env_dir"
    umask 077
    printf '%s=%s\n' "$ENV_KEY_NAME" "$key" > "$env_file"
    chmod 600 "$env_file"

    # Write shell-safe export block to both login and non-login Bash startup files.
    local shell_quoted="${key//\'/\'\\\'\'}"
    local rc_file
    for rc_file in "$HOME/.bashrc" "$HOME/.profile"; do
        touch "$rc_file"
        sed -i '/^# >>> 9router environment >>>$/,/^# <<< 9router environment <<<$/{d;}' "$rc_file"
        {
            echo '# >>> 9router environment >>>'
            printf "export %s='%s'\n" "$ENV_KEY_NAME" "$shell_quoted"
            echo '# <<< 9router environment <<<'
        } >> "$rc_file"
        chmod 600 "$rc_file" 2>/dev/null || true
    done

    # Make variable visible to newly started systemd user services, if available.
    if command -v systemctl >/dev/null 2>&1; then
        systemctl --user import-environment "$ENV_KEY_NAME" 2>/dev/null || true
    fi
    if command -v dbus-update-activation-environment >/dev/null 2>&1; then
        dbus-update-activation-environment --systemd "$ENV_KEY_NAME" 2>/dev/null || true
    fi

    write_ok "Set $ENV_KEY_NAME in current process, ~/.bashrc, ~/.profile, and $env_file."

    # Fetch models
    fetch_models "$url" "$key"

    # Step 1: choose source
    choose_source

    # Step 2: checkbox select
    choose_models

    local default_model="${CHOSEN_IDS[0]}"

    save_backup

    # Write models.json
    local tmp_models="$MODELS_PATH.9router-tmp"
    local tmp_config="$CONFIG_PATH.9router-tmp"

    write_models_json

    # Write config.toml
    write_config_toml "$default_model" "$url" "$key"

