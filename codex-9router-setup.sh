                done
            else
                SOURCE_IDS=("${MODEL_IDS[@]}")
                SOURCE_NAMES=("${MODEL_NAMES[@]}")
                SOURCE_DESCS=("${MODEL_DESCS[@]}")
                SOURCE_OWNED_BY=("${MODEL_OWNED_BY[@]}")
                SOURCE_CTX=("${MODEL_CTX[@]}")
            fi
            return 0
        fi
        _clear_src
        _render_src
    done
}

