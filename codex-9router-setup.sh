    sys.exit(f"Default model '{default}' missing from models.json")
PYEOF
        rm -f "$tmp_models" "$tmp_config"
        die "models.json validation failed."
    }

    mv "$tmp_models" "$MODELS_PATH"
    mv "$tmp_config" "$CONFIG_PATH"
    chmod 600 "$CONFIG_PATH"

    write_head "Configuration written"
    echo "  model                  = \"$default_model\""
    echo '  model_provider         = "9router"'
    echo '  preferred_auth_method  = "apikey"'
    echo '  forced_login_method    = "api"'
    echo '  model_reasoning_effort = "high"'
    echo "  model_catalog_json     = \"$CATALOG_VALUE\""
    echo ""
    echo "  [model_providers.$PROVIDER_ID]"
    echo "  base_url               = \"$url\""
    echo '  wire_api               = "responses"'
    echo "  experimental_bearer_token = (stored in config.toml)"
    echo ""
