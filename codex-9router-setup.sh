fetch_models() {
    local url="$1" key="$2"
    local endpoint="${url%/}/models"
    echo "Reading models: $endpoint"

    local raw
    raw=$(curl -sS --max-time 30 \
        -H "Authorization: Bearer $key" \
        "$endpoint") || die "Cannot reach $endpoint"

    # Support: array, {data:[]}, {models:[]}
    local items
    items=$(echo "$raw" | python3 -c "
import sys, json
d = json.load(sys.stdin)
if isinstance(d, list):
    items = d
elif 'data' in d:
    items = d['data']
elif 'models' in d:
    items = d['models']
else:
    sys.exit(1)
for it in items:
    if isinstance(it, str):
        print(json.dumps({'id':it,'display_name':it,'description':'','owned_by':'','context_window':131072}))
    else:
        mid = it.get('id') or it.get('slug') or it.get('model') or it.get('name','')
        if not mid: continue
        dn = it.get('display_name') or it.get('displayName') or it.get('name') or mid
        desc = it.get('description','')
        owned = it.get('owned_by') or it.get('ownedBy','')
        ctx = 0
        for f in ('context_window','context_length','max_context_tokens','max_input_tokens'):
            v = it.get(f,0)
            if v and str(v).isdigit() and int(v)>0:
                ctx=int(v); break
        if ctx==0: ctx=131072
        print(json.dumps({'id':mid,'display_name':dn,'description':desc,'owned_by':owned,'context_window':ctx}))
" 2>/dev/null | sort -t'"' -k4) || die "Failed to parse /models response."

    MODEL_IDS=(); MODEL_NAMES=(); MODEL_DESCS=(); MODEL_OWNED_BY=(); MODEL_CTX=()
    while IFS= read -r line; do
        [[ -z "$line" ]] && continue
        local mid mdn mdesc mown mctx
        mid=$(echo "$line" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d['id'])" 2>/dev/null)
        mdn=$(echo "$line" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d['display_name'])" 2>/dev/null)
        mdesc=$(echo "$line" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d['description'])" 2>/dev/null)
        mown=$(echo "$line" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d['owned_by'])" 2>/dev/null)
        mctx=$(echo "$line" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d['context_window'])" 2>/dev/null)
        [[ -z "$mid" ]] && continue
        MODEL_IDS+=("$mid")
        MODEL_NAMES+=("${mdn:-$mid}")
        MODEL_DESCS+=("${mdesc:-9Router model: $mid}")
        MODEL_OWNED_BY+=("${mown:-}")
        MODEL_CTX+=("${mctx:-131072}")
    done <<< "$items"

    [[ ${#MODEL_IDS[@]} -eq 0 ]] && die "9Router returned no usable model IDs."
