write_config_toml() {
    local selected_model="$1" url="$2" key="$3"
    local tmp="$CONFIG_PATH.9router-tmp"
    local key_toml="${key//\\/\\\\}"
    key_toml="${key_toml//\"/\\\"}"

    # Strip existing 9router provider and top-level keys we own
    local target_keys="model|model_provider|preferred_auth_method|forced_login_method|model_reasoning_effort|model_catalog_json|profile|oss_provider|openai_base_url|model_context_window|model_auto_compact_token_limit|model_auto_compact_token_limit_scope|base_instructions|model_instructions_file|compact_prompt|experimental_compact_prompt_file|service_tier|model_verbosity|model_reasoning_summary|plan_mode_reasoning_effort|experimental_use_unified_exec_tool"

    local kept=""
    if [[ -f "$CONFIG_PATH" ]]; then
        kept=$(python3 - "$CONFIG_PATH" "$PROVIDER_ID" "$target_keys" <<'PYEOF'
import sys, re

config_path  = sys.argv[1]
provider_id  = sys.argv[2]
target_keys  = set(sys.argv[3].split('|'))

skip_section    = False
seen_first_sect = False
result = []

with open(config_path) as f:
    for line in f:
        line = line.rstrip('\n')
        trim = line.strip()

        m = re.match(r'^\[(.+)\]\s*$', trim)
        if m:
            section = m.group(1).strip('"\'')
            skip_section = (
                section == f"model_providers.{provider_id}" or
                section.startswith(f"model_providers.{provider_id}.") or
                section == "profiles" or
                section.startswith("profiles.")
            )
            seen_first_sect = True
            if not skip_section:
                result.append(line)
            continue

        if skip_section:
            continue

        if not seen_first_sect:
            km = re.match(r'^([^#=]+?)\s*=', trim)
            if km:
                k = km.group(1).strip().strip('"\'')
                if k in target_keys:
                    continue

        result.append(line)

# Strip leading blank lines
while result and not result[0].strip():
    result.pop(0)

print('\n'.join(result))
PYEOF
)
    fi

    {
        echo "model = \"$selected_model\""
        echo "model_provider = \"$PROVIDER_ID\""
        echo 'preferred_auth_method = "apikey"'
        echo 'forced_login_method = "api"'
        echo 'model_reasoning_effort = "high"'
        echo "model_catalog_json = \"$CATALOG_VALUE\""
        echo ""
        [[ -n "$kept" ]] && echo "$kept" && echo ""
        echo "[model_providers.$PROVIDER_ID]"
        echo "name = \"$PROVIDER_ID\""
        echo "base_url = \"$url\""
        echo 'wire_api = "responses"'
        printf 'experimental_bearer_token = "%s"\n' "$key_toml"
    } > "$tmp"
}

