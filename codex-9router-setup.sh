restore_backup() {
    [[ -d "$BACKUP_DIR" ]] || die "Backup not found: $BACKUP_DIR"

    had_config=0; had_models=0
    if [[ -f "$MANIFEST" ]]; then
        grep -q 'original_config_existed=1' "$MANIFEST" && had_config=1
        grep -q 'original_models_existed=1' "$MANIFEST" && had_models=1
    fi

    write_head "Restore configuration that existed before 9Router setup"
    read -rp "Type y to restore: " ans
    [[ "$ans" == "y" || "$ans" == "Y" || "$ans" == "yes" || "$ans" == "YES" ]] || { echo "Cancelled."; return; }

    if [[ $had_config -eq 1 ]]; then
        [[ -f "$BACKUP_CONFIG" ]] || die "Backup config.toml is missing."
        cp "$BACKUP_CONFIG" "$CONFIG_PATH"
    elif [[ -f "$CONFIG_PATH" ]]; then
        rm -f "$CONFIG_PATH"
    fi

    if [[ $had_models -eq 1 ]]; then
        [[ -f "$BACKUP_MODELS" ]] || die "Backup models.json is missing."
        cp "$BACKUP_MODELS" "$MODELS_PATH"
    elif [[ -f "$MODELS_PATH" ]]; then
        rm -f "$MODELS_PATH"
    fi

    rm -rf "$BACKUP_DIR"
    write_ok "Restore complete."
